def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Validate publishable content and links without writing')
    mode.add_argument('--list-urls', action='store_true', help='Print publishable URLs/lastmod as JSON without writing')
    args = parser.parse_args()
    articles = load()
    if not articles: sys.exit('no publishable article in content/conseils')
    by_slug = {a['slug']: a for a in articles}
    header, footer = chrome()
    pages = {f'/conseils/{a["slug"]}': article_page(a, by_slug, header, footer) for a in articles}
    pages['/conseils'] = hub_page(articles, header, footer)
    validate_links(pages)
    if args.list_urls:
        urls = [{'url':f'{ORIGIN}/conseils', 'lastmod':max(a['modified'] for a in articles)}]
        urls += [{'url':f'{ORIGIN}/conseils/{a["slug"]}', 'lastmod':a['modified']} for a in articles]
        print(json.dumps(urls, ensure_ascii=False, indent=2))
        return
    if args.check:
        print(f'Conseils: {len(articles)} publishable articles + hub validated; no files changed.')
        return
    OUT.mkdir(exist_ok=True)
    keep = {f'{a["slug"]}.html' for a in articles} | {'index.html'}
    for old in OUT.glob('*.html'):
        if old.name not in keep and GENERATED in old.read_text(): old.unlink()
    for path, html in pages.items():
        filename = 'index.html' if path == '/conseils' else path.rsplit('/', 1)[1] + '.html'
        (OUT / filename).write_text(html)
    print(f'Conseils: {len(articles)} publishable articles + hub written. Sitemap and service pages unchanged.')


if __name__ == '__main__':
    main()
