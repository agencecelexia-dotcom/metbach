def load():
    articles = []
    for f in sorted(CONTENT.glob('*.json')):
        a = json.loads(f.read_text())
        if a.get('status') not in ('draft', 'publishable'):
            sys.exit(f'{f.name}: status must be draft or publishable')
        if a.get('slug') != f.stem or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', f.stem):
            sys.exit(f'{f.name}: slug must match the file name and use lowercase hyphenated words')
        if a['status'] == 'draft':
            continue
        missing = [k for k in REQUIRED if k not in a]
        if missing: sys.exit(f'{f.name}: missing {missing}')
        if a['slug'] != f.stem: sys.exit(f'{f.name}: slug must match the file name')
        if a['category'] not in CATEGORIES: sys.exit(f'{f.name}: unknown category {a["category"]}')
        if len(a['title']) > 60: sys.exit(f'{f.name}: title over 60 characters')
        if not 120 <= len(a['description']) <= 160: sys.exit(f'{f.name}: description must be 120–160 characters')
        try:
            published, modified, reviewed = (date.fromisoformat(a[k]) for k in ('published', 'modified', 'reviewed'))
            if published > modified or reviewed > modified or modified > date.today():
                raise ValueError('inconsistent publication/review dates')
        except (TypeError, ValueError) as error:
            sys.exit(f'{f.name}: invalid dates ({error})')
        if not a['sections'] or not a['faq'] or not a['sources']:
            sys.exit(f'{f.name}: sections, faq and sources must not be empty')
        ids = [s['id'] for s in a['sections']]
        if len(ids) != len(set(ids)) or set(ids) & {'main', 'questions', 'devis', 'sources'}:
            sys.exit(f'{f.name}: duplicate or reserved section id')
        if a['service']['form'] not in ('couverture', 'nettoyage-toiture', 'isolation-exterieure', 'maconnerie', 'piscine'):
            sys.exit(f'{f.name}: unsupported service form value')
        if not a['service'].get('intro'):
            sys.exit(f'{f.name}: contextual service intro required')
        if any(not s['url'].startswith('https://') for s in a['sources']):
            sys.exit(f'{f.name}: source URL must use https')
        visible = [a['h1'], a['lead'], a['answer'], a['eyebrow']] + [text_of(x['html']) + x['h2'] for x in a['sections']] \
            + [q['q'] + q['a'] for q in a['faq']] + [a['service']['intro']]
        if any("'" in v for v in visible): sys.exit(f'{f.name}: straight apostrophe in visible text (use ’)')
        articles.append(a)
    slugs = {a['slug'] for a in articles}
    for a in articles:
        for r in a['related']:
            if r not in slugs: sys.exit(f'{a["slug"]}: related article {r} is absent or not publishable')
    return articles


def validate_links(pages):
    """Check generated navigation, article links and fragments before writing any page."""
    for path, html in pages.items():
        parsed = Links()
        parsed.feed(html)
        for href in parsed.hrefs:
            url = urlsplit(href)
            if url.scheme or url.netloc:
                continue
            target = url.path or path
            if not target.startswith('/'):
                sys.exit(f'{path}: relative link is not supported: {href}')
            if target in pages:
                target_html = pages[target]
            elif target.startswith('/conseils/') or target == '/conseils':
                sys.exit(f'{path}: advice link is absent or draft: {href}')
            else:
                candidates = [ROOT / (target.strip('/') + '.html'), ROOT / target.strip('/') / 'index.html']
                if target == '/': candidates = [ROOT / 'index.html']
                file = next((p for p in candidates if p.is_file()), None)
                if not file: sys.exit(f'{path}: broken internal link: {href}')
                target_html = file.read_text()
            if url.fragment:
                target_parsed = Links()
                target_parsed.feed(target_html)
                if url.fragment not in target_parsed.ids:
                    sys.exit(f'{path}: missing target fragment: {href}')


