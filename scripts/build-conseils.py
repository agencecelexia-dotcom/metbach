class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs = []
        self.ids = set()

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        if tag == 'a' and 'href' in values:
            self.hrefs.append(values['href'])
        if 'id' in values:
            self.ids.add(values['id'])


def fr_date(iso):
    y, m, d = iso.split('-')
    return f'{int(d)}{"er" if d == "01" else ""} {MONTHS[int(m) - 1]} {y}'


def text_of(html):
    return ' '.join(re.sub(r'<[^>]+>', ' ', html).split())


def chrome():
    """Header, mobile menu and footer from the city template, without the city parameter."""
    src = (ROOT / 'villes' / 'sciez.html').read_text()
    body_start = src.index('<a href="#main"')
    header = src[body_start:src.index('<main')]
    footer = src[src.index('<footer'):src.index('</body>')]
    for part in ('?city=sciez', '&amp;city=sciez'):
        header = header.replace(part, '')
        footer = footer.replace(part, '')
    return header, footer


def jsonld(graph):
    return '<script type="application/ld+json">' + json.dumps(
        {'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False, indent=2) + '</script>'


